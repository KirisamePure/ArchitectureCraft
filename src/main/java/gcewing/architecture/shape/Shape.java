  public enum Symmetry {
    Bilateral,
    Unilateral,
    Quadrilateral,
    None
  }

  public final int id, materialUsed, itemsProduced, occlusionMask;
  public final String title, model, profile;
  public final boolean underneath, offset, banister;
  public final Symmetry symmetry;

  Shape(
      int id,
      String title,
      String model,
      int used,
      int made,
      boolean underneath,
      boolean offset,
      Symmetry symmetry,
      int mask,
      String profile,
      boolean banister) {
    this.id = id;
    this.title = title;
    this.model = model;
    materialUsed = used;
    itemsProduced = made;
    this.underneath = underneath;
    this.offset = offset;
    this.symmetry = symmetry;
    occlusionMask = mask;
    this.profile = profile;
    this.banister = banister;
  }

  public String key() {
    return name().toLowerCase(Locale.ROOT);
  }

  public boolean window() {
    return id >= 30 && id <= 32;
  }

  public boolean roof() {
    return model.equals("roof");
  }

  public boolean glowing() {
    return id >= 103 && id <= 114;
  }

  public boolean acceptsCladding() {
    return roof()
        || !window()
            && Mesh.model("shape/" + model).triangles().stream().anyMatch(t -> t.material() >= 2);
  }

  public double placementOffset() {
    if (banister) return 6 / 16.;
    var boxes = Mesh.model("shape/" + model).boxes();
    double min = boxes.stream().mapToDouble(Mesh.Box::x0).min().orElse(0),
        max = boxes.stream().mapToDouble(Mesh.Box::x1).max().orElse(1);
    return (1 - (max - min)) * .5;
  }

  public static Shape byId(int id) {
    return Arrays.stream(values()).filter(s -> s.id == id).findFirst().orElse(RoofTile);
  }
